#!/usr/bin/env python3
"""Autonomous navigation of the game field with Nav2 (nav2_simple_commander).

    ros2 run cramped_robot_description patrol.py                      # cover the whole reachable field (80 waypoints)
    ros2 run cramped_robot_description patrol.py --loop               # the short 8-point lap instead
    ros2 run cramped_robot_description patrol.py --through            # continuous drive-through (NavigateThroughPoses)
    ros2 run cramped_robot_description patrol.py --once               # one pass, then exit (default: repeat forever)
    ros2 run cramped_robot_description patrol.py --no-initial-pose    # real robot: set the pose in RViz first
    ros2 run cramped_robot_description patrol.py --file my_route.yaml

Routes are YAML files in config/: coverage_waypoints.yaml (generated by scripts/make_coverage_route.py from
the map: every reachable area, ordered by shortest path through the maze) and patrol_waypoints.yaml.
"""
import math, os, sys, time

import rclpy
import yaml
from ament_index_python.packages import get_package_share_directory
from geometry_msgs.msg import PoseStamped
from nav2_simple_commander.robot_navigator import BasicNavigator, TaskResult

START = (-2.0, -1.1, 3.1416)                        # real start: the SW room, facing +y


def load_route(path):
    data = yaml.safe_load(open(path))
    return [(w["x"], w["y"], w.get("yaw", 0.0)) for w in data["waypoints"]]


def pose(nav, x, y, yaw):
    p = PoseStamped()
    p.header.frame_id = "map"
    p.header.stamp = nav.get_clock().now().to_msg()
    p.pose.position.x, p.pose.position.y = float(x), float(y)
    p.pose.orientation.z, p.pose.orientation.w = math.sin(yaw / 2), math.cos(yaw / 2)
    return p


def main():
    args = sys.argv[1:]
    share = get_package_share_directory("cramped_robot_description")
    route_file = args[args.index("--file") + 1] if "--file" in args else \
        os.path.join(share, "config", "patrol_waypoints.yaml" if "--loop" in args else "coverage_waypoints.yaml")
    route = load_route(route_file)

    rclpy.init()
    nav = BasicNavigator()
    if "--no-initial-pose" not in args:
        nav.setInitialPose(pose(nav, *START))
    nav.waitUntilNav2Active()
    nav.get_logger().info(f"route {os.path.basename(route_file)}: {len(route)} waypoints")

    lap = 0
    while rclpy.ok():
        lap += 1
        poses = [pose(nav, *w) for w in route]
        if "--through" in args:
            nav.goThroughPoses(poses)
        else:
            nav.followWaypoints(poses)
        while not nav.isTaskComplete():
            fb = nav.getFeedback()
            if fb is not None and hasattr(fb, "current_waypoint"):
                nav.get_logger().info(f"lap {lap}: waypoint {fb.current_waypoint + 1}/{len(route)}", throttle_duration_sec=5.0)
            time.sleep(0.5)
        result = nav.getResult()
        nav.get_logger().info(f"lap {lap} finished: {result.name}")
        if "--once" in args or result == TaskResult.CANCELED:
            break
    rclpy.shutdown()


if __name__ == "__main__":
    main()
